#!/usr/bin/env python
import math
import os
import random
import sys
import time

import pandas as pd

# expyrimenter is a git submodule under external/expyrimenter/ (see
# .gitmodules) -- it is its own top-level "Experiments" package, so it
# needs its own sys.path entry rather than living at the repo root.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "external", "expyrimenter"))
from Experiments.Registry import Registry
from Experiments.Backend import JoblibRunnerBackend, SequentialRunnerBackend

from Graph.Graph import Graph
from EA.Operators import USGMutatorWithPresorting, XORCrossoverSampled
from EA.utils.RandomWeightSampler import RandomWeightSampler
from EA.utils.EdgeSampler import EdgeSamplerUniform
from EA.utils.EdgeOrderer import EdgeOrdererExact
from Graph.generators.RandomSpanningTreeGenerator import RandomSpanningTreeGenerator
from EA.Algorithms import NSGA2

'''
P_CROSSOVER SWEEP BY INSTANCE CLASS (Mode 1, "either/or")

Sweeps NSGA2's Mode 1 mixing weight p_crossover ("either/or": each offspring
is generated by crossover with probability p_crossover and by mutation with
probability 1 - p_crossover, never both -- see EA.Algorithms.NSGA2's
docstring) from 0.0 to 1.0 in steps of 0.1, fixing the operator pair to XOR
(pure) + USGS-PRE (the strongest hybrid pairing found in the earlier
crossover/mutation comparison), across one representative instance per class
C1-C4 (the "_6" instance of each class, same as
hybrid_modes_by_class_runner_expyrimenter.py and the single-instance
long-run comparison it generalizes).

p_crossover = 0.0 and 1.0 are outside NSGA2's Mode 1 assertion range
(0 < p_crossover < 1, since "always X, never Y" is the "neither given" mode,
not Mode 1's per-offspring coin flip) but are behaviourally IDENTICAL to it
at the boundary (random.random() is always < 1.0 and never < 0.0), so they
are constructed directly as the pure-mutation / pure-crossover edge cases:
p_crossover = 0.0 -> mutator only, no crossover object at all;
p_crossover = 1.0 -> crossover only, no mutator object at all. This lets the
sweep cover the full [0, 1] range including both pure-operator endpoints
alongside the hybrid mixture in between, e.g. to check for an inverted-U
("does some crossover+mutation mixture beat either pure operator alone") per
instance class, and whether pure crossover beats pure mutation.
'''

REGISTRY_PATH = "results/approximations/ex09_pc_sweep_by_class"

CLASS_INSTANCES = [
    "instances/100/CLASS1_100_4950_0_2_UNG_CEG_RWG-RWG_6.graph",
    "instances/100/CLASS2_100_4950_0_2_UNG_CEG_CONCWG_6.graph",
    "instances/100/CLASS3_100_4950_0_2_UNG_CEG_-0.95--CORWG_6.graph",
    "instances/100/CLASS4_100_4950_0_2_UNG_CEG_0.95--CORWG_6.graph",
]

PC_VALUES = [round(i / 10, 1) for i in range(11)]  # 0.0, 0.1, ..., 1.0


def setup_initializer(graph):
    return lambda: RandomSpanningTreeGenerator.sample(graph, method="broder")


def setup_crossover(graph, n):
    sigma = n // 2
    edge_orderer = EdgeOrdererExact()
    edge_sampler = EdgeSamplerUniform(graph.get_edges())
    weight_sampler = RandomWeightSampler()
    crossover_object = XORCrossoverSampled(graph, edge_sampler, edge_orderer, weight_sampler, sigma=sigma)
    return lambda x, y: crossover_object.create(x, y)


def setup_mutator(graph, n):
    sigma = math.ceil(math.log(n) * math.log(n))
    mutator_object = USGMutatorWithPresorting(graph, sigma=sigma, L=n)
    return lambda x: mutator_object.create(x)


def objective_fun(tree):
    return tree.get_sum_of_edge_costs()


def make_runner(registry_path, max_gens=None):
    """
    Builds the runner function expyrimenter calls as runner(jobid, params).
    params["p_crossover"] selects the Mode 1 mixing weight (0.0 and 1.0 are
    the pure-mutation / pure-crossover edge cases, see module docstring);
    max_gens overrides the generation budget for quick smoke tests; leave
    None in production to use the 100-generation default shared with the
    other ex0X designs.
    """

    def run_experiment(jobid, params):
        path_to_instance = params["instance"]
        pc = float(params["p_crossover"])
        repl = int(params["repl"])

        # --- common random numbers: same seed for repl=k across all pc values/instances ---
        random.seed(repl)
        seed = random.randint(1, 1_000_000)
        random.seed(seed)

        graph = Graph.import_grapherator_format(path_to_instance)
        n = graph.get_n()

        MU = 100
        LAMBDAA = 100
        gens = max_gens if max_gens is not None else 100
        max_evals = MU + LAMBDAA * gens

        crossover = setup_crossover(graph, n)
        mutator = setup_mutator(graph, n)

        if pc <= 0.0:
            algo_kwargs = dict(crossover=None, mutator=mutator)
        elif pc >= 1.0:
            algo_kwargs = dict(crossover=crossover, mutator=None)
        else:
            algo_kwargs = dict(crossover=crossover, mutator=mutator, p_crossover=pc)

        algorithm = NSGA2(
            mu=MU,
            lambdaa=LAMBDAA,
            initializer=setup_initializer(graph),
            objective_fun=objective_fun,
            max_evals=max_evals,
            log_every=10,
            **algo_kwargs)

        start_time = time.time()
        algorithm.run()
        total_time = time.time() - start_time

        out_path = os.path.join(registry_path, "experiments", str(jobid))
        os.makedirs(out_path, exist_ok=True)
        algorithm.write_result(out_path, total_time)

        return {"runtime": total_time}

    return run_experiment


def build_registry(registry_path, instances, pc_values, repls, predicate=None, backend=None):
    reg = Registry(path=registry_path, overwrite=True, backend=backend or SequentialRunnerBackend())
    reg.add_jobs(instance=instances, p_crossover=pc_values, repl=repls,
                 predicate=predicate or (lambda params: True))
    return reg


if __name__ == "__main__":
    repls = list(range(1, 11))  # 10 independent reps, as in the other ex0X designs

    reg = build_registry(REGISTRY_PATH, CLASS_INSTANCES, PC_VALUES, repls,
                          backend=JoblibRunnerBackend(ncores=os.cpu_count() - 1))
    print(reg)

    runner = make_runner(REGISTRY_PATH)  # max_gens=None -> full 100-generation budget
    reg.run(runner, batchsize=3 * (os.cpu_count() - 1))

    print(reg)
    print("failed:", reg.get_failed())
    if reg.get_failed():
        reg.show_logs(reg.get_failed())

    res = reg.get_results(jobids=reg.get_done(), simplify=True)
    print(pd.DataFrame(res).to_string())
